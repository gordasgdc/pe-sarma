#!/bin/bash
# End-to-end probe on a real Mac: capture-folder takeover and restoration,
# a screenshot read by OCR and indexed, clipboard text, private clipboard
# types, a crash and relaunch, an unreadable watched folder, and no sockets.
# It changes the macOS screenshot settings temporarily and puts them back;
# it overwrites the current clipboard. Quit other copies of the app first.
# Usage: PESARMA_BUILD_DIR=/path PESARMA_EVIDENCE_DIR=/path scripts/probe-e2e.sh <probe.png>
set -uo pipefail
cd "$(dirname "$0")/.."
APP="${PESARMA_BUILD_DIR:?}/PeSarma.app"; EV="${PESARMA_EVIDENCE_DIR:?}"; PNG="${1:?probe image}"
DOM=dev.gordas.PeSarma; SUP="$HOME/Library/Application Support/PeSarma"; LOG="$HOME/Library/Logs/PeSarma/PeSarma.log"
mkdir -p "$EV"; REPORT="$EV/probe-e2e-report.txt"; : > "$REPORT"
PASS=0; FAIL=0
ok() { echo "PASS: $1" | tee -a "$REPORT"; PASS=$((PASS+1)); }
bad() { echo "FAIL: $1" | tee -a "$REPORT"; FAIL=$((FAIL+1)); }
check() { if eval "$2"; then ok "$1"; else bad "$1"; fi; }
prefs() { defaults read com.apple.screencapture 2>/dev/null | grep -v last-analytics-stamp; }
wait_for() { for _ in $(seq 1 "${3:-30}"); do eval "$1" && return 0; sleep 1; done; return 1; }
alive() { pgrep -f "$APP/Contents/MacOS/PeSarma" >/dev/null; }
quit_app() { osascript -e "tell application id \"$DOM\" to quit" >/dev/null 2>&1; wait_for '! alive' x 15; }

pgrep -f -i 'tendedero' >/dev/null && { echo "Quit Tendedero first"; exit 2; }
alive && { echo "Quit Pe sârmă first"; exit 2; }
prefs > "$EV/probe-prefs-before.txt"
defaults delete $DOM >/dev/null 2>&1; rm -rf "$SUP"
defaults write $DOM welcomed -bool true
defaults write $DOM inboxEnabled -bool true
defaults write $DOM inboxOffered -bool true
defaults write $DOM copyingOffered -bool true
defaults write $DOM loginOfferedVersion -string "$(cat VERSION)"
defaults write $DOM clipboardTextEnabled -bool true
defaults write $DOM clipboardLinksEnabled -bool true
LOC="$SUP/Screenshots"

echo "== A. launch, takeover, hang, OCR, clipboard, quit" | tee -a "$REPORT"
open -g "$APP"; wait_for 'alive' x 15
check "app starts" alive
wait_for '[ "$(defaults read com.apple.screencapture location-screenshot 2>/dev/null)" = "$LOC" ]' x 10
check "screenshot location points to the app folder" '[ "$(defaults read com.apple.screencapture location-screenshot 2>/dev/null)" = "$LOC" ]'
check "floating thumbnail is off" '[ "$(defaults read com.apple.screencapture show-thumbnail 2>/dev/null)" = 0 ]'
sleep 4
mkdir -p "$LOC"; cp "$PNG" "$LOC/Captura probă.png"
check "OCR indexes Romanian diacritics (search folds to ascii)" 'wait_for "grep -q -i sedinta \"$SUP/SearchIndex.json\" 2>/dev/null" x 40'
check "OCR text kept without diacritics for search (sarma)" 'grep -q -i "pe sarma" "$SUP/SearchIndex.json"'
before=$(ls "$SUP/Notes" 2>/dev/null | wc -l)
swift scripts/pasteboard-write.swift "Textul meu de probă cu șarpe" 2>/dev/null
check "copied text hangs as a note" 'wait_for "[ \$(ls \"$SUP/Notes\" 2>/dev/null | wc -l) -gt $before ]" x 10'
n1=$(ls "$SUP/Notes" | wc -l)
swift scripts/pasteboard-write.swift "parola-secreta-123" concealed 2>/dev/null; sleep 3
check "concealed clipboard type is not kept" '[ $(ls "$SUP/Notes" | wc -l) -eq '"$n1"' ] && ! grep -rqs "parola-secreta" "$SUP/Notes"'
swift scripts/pasteboard-write.swift "temporar-transient-456" transient 2>/dev/null; sleep 3
check "transient clipboard type is not kept" '[ $(ls "$SUP/Notes" | wc -l) -eq '"$n1"' ]'
swift scripts/pasteboard-write.swift "autogenerat-789" autogenerated 2>/dev/null; sleep 3
check "auto-generated clipboard type is not kept" '[ $(ls "$SUP/Notes" | wc -l) -eq '"$n1"' ]'
swift scripts/pasteboard-write.swift "https://gordas.dev/pe-sarma/" 2>/dev/null; sleep 3
check "copied link hangs" '[ $(ls "$SUP/Notes" | wc -l) -gt '"$n1"' ]'
PID=$(pgrep -f "$APP/Contents/MacOS/PeSarma" | head -1)
check "no network sockets open (offline-capable)" '[ -z "$(lsof -nP -i -a -p $PID 2>/dev/null)" ]'
check "no secrets or content in the log" '! grep -q -i -E "parola-secreta|transient|autogenerat|Textul meu|șarpe" "$LOG"'
quit_app
check "app quits" '! alive'
check "screenshot settings restored after quit" '[ "$(prefs)" = "$(cat "$EV/probe-prefs-before.txt")" ]'
grep -q 'inbox.restore' "$LOG" && ok "restore event logged" || bad "restore event logged"

echo "== B. crash while applied, relaunch, quit" | tee -a "$REPORT"
open -g "$APP"; wait_for 'alive' x 15; sleep 3
check "settings applied again" '[ "$(defaults read com.apple.screencapture location-screenshot 2>/dev/null)" = "$LOC" ]'
pkill -9 -f "$APP/Contents/MacOS/PeSarma"; sleep 2
check "after kill -9 the folder is still applied (known: nothing could restore it)" '[ "$(defaults read com.apple.screencapture location-screenshot 2>/dev/null)" = "$LOC" ]'
open -g "$APP"; wait_for 'alive' x 15; sleep 3
quit_app
check "relaunch then quit restores the original settings" '[ "$(prefs)" = "$(cat "$EV/probe-prefs-before.txt")" ]'

echo "== C. unreadable watched folder (access denied)" | tee -a "$REPORT"
DENY="$EV/denied-folder"; rm -rf "$DENY"; mkdir -p "$DENY"; chmod 000 "$DENY"
defaults write $DOM extraFolders -array "$DENY"
open -g "$APP"; wait_for 'alive' x 15; sleep 4
check "app keeps running when a folder cannot be read" alive
check "denial logged as an event without the path" 'grep -q "watch.unavailable" "$LOG" && ! grep -q "denied-folder" "$LOG"'
quit_app; chmod 755 "$DENY"; rmdir "$DENY"
check "settings restored after the denied-folder run" '[ "$(prefs)" = "$(cat "$EV/probe-prefs-before.txt")" ]'

defaults delete $DOM >/dev/null 2>&1; rm -rf "$SUP"
echo "RESULT: $PASS passed, $FAIL failed" | tee -a "$REPORT"
[ "$FAIL" -eq 0 ]
